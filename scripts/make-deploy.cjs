// Builds a ready-to-copy production folder:  deploy/central-user-service/  (+ deploy/central-user-service.zip)
//
//   node scripts/make-deploy.cjs
//
// Contents (copy the whole folder to the server, e.g. /var/www/html/central-user-service):
//   src/ db/ public/ examples/   the service
//   node_modules/                production dependencies (pure JS, run on Ubuntu as-is)
//   .env                         production settings: current .env + production overrides below
//   keys/                        the production RS256 signing key pair (generated once, then kept)
//   apache/                      Apache site for https://<DOMAIN>
//   ecosystem.config.cjs, README.md, DEPLOY.md, logs/
//
// .env and keys/ are secrets: deploy/ is git-ignored. Re-running keeps the existing production .env
// and keys (a new key would sign everyone out of every app).
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const { execSync } = require('child_process');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'deploy', 'central-user-service');

const PROD = {
  DOMAIN: process.env.DEPLOY_DOMAIN || 'users.wockregenerative.com',
  SERVER_IP: '192.168.3.112',
  APP_PORT: process.env.DEPLOY_PORT || '5020', // internal port; Apache serves 443
};

const run = (cmd, cwd) => {
  console.log(`> ${cmd}   (${path.relative(ROOT, cwd) || '.'})`);
  execSync(cmd, { cwd, stdio: 'inherit' });
};
const copy = (from) => fs.cpSync(path.join(ROOT, from), path.join(OUT, from), { recursive: true });

// Keep what a previous build produced: the production .env and signing keys.
const keep = {};
for (const f of ['.env', 'keys/private.pem', 'keys/public.pem']) {
  const p = path.join(OUT, f);
  if (fs.existsSync(p)) keep[f] = fs.readFileSync(p);
}

// 1. Fresh output folder.
fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(path.join(OUT, 'logs'), { recursive: true });

// 2. Code + production-only dependencies.
for (const f of ['src', 'db', 'public', 'examples', 'package.json', 'package-lock.json', 'ecosystem.config.cjs', '.env.example', '.gitignore', 'README.md', 'DEPLOY.md']) {
  if (fs.existsSync(path.join(ROOT, f))) copy(f);
}
run('npm ci --omit=dev --no-audit --no-fund', OUT);

// 3. Production .env = current .env with production overrides (or the previous build's, unchanged).
if (keep['.env']) {
  fs.writeFileSync(path.join(OUT, '.env'), keep['.env']);
  console.log('Kept the existing production .env unchanged.');
} else {
  let env = fs.readFileSync(path.join(ROOT, '.env'), 'utf8');
  const set = (key, value) => {
    const re = new RegExp(`^${key}=.*$`, 'm');
    env = re.test(env) ? env.replace(re, `${key}=${value}`) : `${env.trimEnd()}\n${key}=${value}\n`;
  };
  set('PORT', PROD.APP_PORT);
  set('PUBLIC_URL', `https://${PROD.DOMAIN}`);
  set('OTP_DELIVERY', 'email');
  set('TRUST_PROXY', '1');
  // Developer-PC-only lines: local database fallback and the read-only seed sources.
  env = env
    .replace(/^# Local PostgreSQL fallback.*\n# DATABASE_URL=[^\n]*\n/m, '')
    .replace(/^# Online \(D2D\) database[^\n]*\nSOURCE_DATABASE_URL=[^\n]*\n/m, '')
    .replace(/\n# BIONX PULSE login database[^\n]*\nBIONX_USERS_DATABASE_URL=[^\n]*\n/m, '\n')
    .replace(/^# Central User Service — LOCAL development settings \(this PC\)\.$/m, `# Central User Service — production (${PROD.DOMAIN}, server ${PROD.SERVER_IP})`);
  if (/127\.0\.0\.1|localhost/.test((env.match(/^DATABASE_URL=(.*)$/m) || [])[1] || '')) {
    throw new Error('DATABASE_URL in .env is a local database; point it at the production database first.');
  }
  fs.writeFileSync(path.join(OUT, '.env'), `# Generated by scripts/make-deploy.cjs on ${new Date().toISOString()}\n${env}`);
  console.log('Wrote the production .env.');
}

// 4. Production signing key: kept from the last build, otherwise a new pair (not the developer PC's).
fs.mkdirSync(path.join(OUT, 'keys'), { recursive: true });
if (keep['keys/private.pem']) {
  fs.writeFileSync(path.join(OUT, 'keys', 'private.pem'), keep['keys/private.pem'], { mode: 0o600 });
  fs.writeFileSync(path.join(OUT, 'keys', 'public.pem'), keep['keys/public.pem']);
  console.log('Kept the existing production signing key.');
} else {
  const { privateKey, publicKey } = crypto.generateKeyPairSync('rsa', {
    modulusLength: 2048,
    publicKeyEncoding: { type: 'spki', format: 'pem' },
    privateKeyEncoding: { type: 'pkcs8', format: 'pem' },
  });
  fs.writeFileSync(path.join(OUT, 'keys', 'private.pem'), privateKey, { mode: 0o600 });
  fs.writeFileSync(path.join(OUT, 'keys', 'public.pem'), publicKey);
  console.log('Generated a new production signing key (keys/private.pem). Keep it across redeploys.');
}

// 5. Apache site (same wildcard certificate as bionxpulse.wockregenerative.com).
fs.mkdirSync(path.join(OUT, 'apache'), { recursive: true });
fs.writeFileSync(
  path.join(OUT, 'apache', `${PROD.DOMAIN}.conf`),
  `# Central User Service: https://${PROD.DOMAIN} -> pm2 app central-user-service on 127.0.0.1:${PROD.APP_PORT}
# Needs: sudo a2enmod proxy proxy_http ssl headers rewrite

<VirtualHost *:80>
    ServerName ${PROD.DOMAIN}
    RewriteEngine On
    RewriteRule ^ https://%{SERVER_NAME}%{REQUEST_URI} [END,NE,R=permanent]
</VirtualHost>

<IfModule mod_ssl.c>
<VirtualHost *:443>
    ServerName ${PROD.DOMAIN}

    SSLEngine on
    SSLCertificateFile      /etc/ssl/certs/wildcard_wockregenerative_com_fullchain.crt
    SSLCertificateKeyFile   /etc/ssl/private/wildcard.wockregenerative.com.key

    ProxyRequests     Off
    ProxyPreserveHost On
    # Synapse syncs can take ~1 minute
    ProxyTimeout      180
    ProxyPass         / http://127.0.0.1:${PROD.APP_PORT}/ timeout=180
    ProxyPassReverse  / http://127.0.0.1:${PROD.APP_PORT}/
    RequestHeader set X-Forwarded-Proto "https"

    ErrorLog  \${APACHE_LOG_DIR}/central_user_service_error.log
    CustomLog \${APACHE_LOG_DIR}/central_user_service_access.log combined
</VirtualHost>
</IfModule>
`
);

// 6. Zip for upload (deploy/central-user-service.zip, top-level folder central-user-service/).
const zip = path.join(ROOT, 'deploy', 'central-user-service.zip');
fs.rmSync(zip, { force: true });
// tar (built into Windows 10+) writes standard zip paths with '/'; PowerShell 5's Compress-Archive
// writes '\', which unzip on Ubuntu reports as an error.
run(process.platform === 'win32' ? 'tar.exe -a -c -f central-user-service.zip central-user-service' : 'zip -qr central-user-service.zip central-user-service', path.join(ROOT, 'deploy'));

const size = (dir) => fs.readdirSync(dir, { withFileTypes: true }).reduce((n, e) => n + (e.isDirectory() ? size(path.join(dir, e.name)) : fs.statSync(path.join(dir, e.name)).size), 0);
console.log(`\nDeploy folder ready: ${path.relative(ROOT, OUT)}  (${(size(OUT) / 1024 / 1024).toFixed(1)} MB)`);
console.log(`Zip: ${path.relative(ROOT, zip)}  (${(fs.statSync(zip).size / 1024 / 1024).toFixed(1)} MB)`);
console.log(`Copy it to the server (${PROD.SERVER_IP}) and follow DEPLOY.md.`);
